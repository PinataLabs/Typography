using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using PinataLabs.Typography.Unicode;

namespace UnicodeTrieGenerator;

/// <content>
/// Contains code to generate the vowel sequences that the Indic and universal shapers break with a dotted circle.
/// </content>
public static partial class Generator
{
    /// <summary>
    /// Generates <c>VowelConstraintData</c> from <c>IndicShapingInvalidCluster.txt</c>, as
    /// <c>gen-vowel-constraints.py</c> of HarfBuzz 15.0.0 generates <c>_hb_preprocess_text_vowel_constraints</c>. Each
    /// sequence belongs to the script of its first code point in <c>Scripts.txt</c>.
    /// </summary>
    private static void GenerateVowelConstraints()
    {
        Dictionary<int, ScriptClass> scripts = [];
        ForEachRange("Scripts.txt", (start, end, value) =>
        {
            for (int i = start; i <= end; i++)
            {
                scripts[i] = ScriptMap[value];
            }
        });

        // The scripts in the order in which the file first names them.
        List<(ScriptClass Script, ConstraintSet Set)> sets = [];
        using (StreamReader reader = GetStreamReader("IndicShapingInvalidCluster.txt"))
        {
            string? line;
            while ((line = reader.ReadLine()) != null)
            {
                List<int> sequence = line.Split('#')[0].Split(';')[0]
                    .Split(' ', StringSplitOptions.RemoveEmptyEntries)
                    .Select(ParseHexInt)
                    .ToList();

                if (sequence.Count == 0)
                {
                    continue;
                }

                if (sequence.Count < 2)
                {
                    throw new InvalidOperationException($"The sequence {line.Trim()} is too short to break.");
                }

                ScriptClass script = scripts[sequence[0]];
                int index = sets.FindIndex(x => x.Script == script);
                if (index < 0)
                {
                    sets.Add((script, new ConstraintSet(sequence)));
                }
                else
                {
                    sets[index].Set.Add(sequence);
                }
            }
        }

        using FileStream fileStream = GetStreamWriter("VowelConstraintData.Generated.cs");
        using var writer = new StreamWriter(fileStream);

        writer.WriteLine("// Copyright (c) PinataLabs.");
        writer.WriteLine("// Licensed under the Apache License, Version 2.0.");
        writer.WriteLine();
        writer.WriteLine("// <auto-generated />");
        writer.WriteLine("namespace PinataLabs.Typography.Unicode.Resources;");
        writer.WriteLine();
        writer.WriteLine("internal static class VowelConstraintData");
        writer.WriteLine("{");

        foreach ((ScriptClass script, ConstraintSet set) in sets)
        {
            writer.WriteLine($"    private static readonly VowelConstraint[] {script} =");
            writer.WriteLine("    [");
            foreach ((List<int> codePoints, int circleIndex) in set.GetConstraints())
            {
                writer.WriteLine($"        new([{string.Join(", ", codePoints.Select(c => $"0x{c:X4}"))}], {circleIndex}),");
            }

            writer.WriteLine("    ];");
            writer.WriteLine();
        }

        writer.WriteLine("    public static VowelConstraint[] GetConstraints(ScriptClass script) => script switch");
        writer.WriteLine("    {");
        foreach ((ScriptClass script, _) in sets)
        {
            writer.WriteLine($"        ScriptClass.{script} => {script},");
        }

        writer.WriteLine("        _ => [],");
        writer.WriteLine("    };");
        writer.WriteLine("}");
    }

    /// <summary>
    /// The prohibited sequences of one script, as the <c>ConstraintSet</c> class of <c>gen-vowel-constraints.py</c> holds
    /// them. A set is one sequence, or the sets of the sequences that follow each first code point. A sequence that
    /// starts another one in the same set replaces it, so the generated function matches the shorter one.
    /// </summary>
    private sealed class ConstraintSet
    {
        private List<int>? sequence;

        private SortedDictionary<int, ConstraintSet>? next;

        public ConstraintSet(List<int> sequence) => this.sequence = sequence;

        public void Add(List<int> constraint)
        {
            if (constraint.Count == 0)
            {
                return;
            }

            if (this.sequence is not null)
            {
                if (StartsWith(this.sequence, constraint))
                {
                    this.sequence = constraint;
                }
                else if (!StartsWith(constraint, this.sequence))
                {
                    this.next = new() { [this.sequence[0]] = new ConstraintSet(this.sequence[1..]) };
                    this.sequence = null;
                }
            }

            if (this.next is not null)
            {
                if (this.next.TryGetValue(constraint[0], out ConstraintSet? set))
                {
                    set.Add(constraint[1..]);
                }
                else
                {
                    this.next[constraint[0]] = new ConstraintSet(constraint[1..]);
                }
            }
        }

        /// <summary>
        /// Gets the sequences that the generated function of HarfBuzz matches, each with the index of the code point
        /// that it outputs the dotted circle before.
        /// </summary>
        /// <returns>The sequences.</returns>
        public List<(List<int> CodePoints, int CircleIndex)> GetConstraints()
        {
            List<(List<int> CodePoints, int CircleIndex)> constraints = [];
            this.AddConstraints([], constraints);
            return constraints;
        }

        // The depth is the index that the generator passes to __str__: the index of the code point this set starts at.
        private void AddConstraints(List<int> prefix, List<(List<int> CodePoints, int CircleIndex)> constraints)
        {
            int depth = prefix.Count;
            if (this.sequence is not null)
            {
                // The generator emits a match without the following code points only at these depths.
                if ((this.sequence.Count == 0 && depth != 2) || (this.sequence.Count == 1 && depth != 1))
                {
                    throw new InvalidOperationException(
                        $"gen-vowel-constraints.py cannot match the sequence {string.Join(" ", prefix.Concat(this.sequence).Select(c => $"{c:X4}"))}.");
                }

                // A longer sequence outputs the code points before its index and the one at its index past the circle,
                // and leaves the rest to the next match.
                int circleIndex = this.sequence.Count < 2 ? 1 : depth + 1;
                constraints.Add(([.. prefix, .. this.sequence], circleIndex));
                return;
            }

            foreach ((int codePoint, ConstraintSet set) in this.next!)
            {
                set.AddConstraints([.. prefix, codePoint], constraints);
            }
        }

        private static bool StartsWith(List<int> sequence, List<int> prefix)
            => prefix.Count <= sequence.Count && sequence.Take(prefix.Count).SequenceEqual(prefix);
    }
}
