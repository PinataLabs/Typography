using System.IO;

namespace UnicodeTrieGenerator;

/// <content>
/// Contains code to generate the class that reports the Unicode version of the tries.
/// </content>
public static partial class Generator
{
    /// <summary>
    /// Generates <c>UnicodeInfo</c>, with the Unicode version that the rule files are of.
    /// </summary>
    /// <param name="version">The Unicode version of the rule files.</param>
    public static void GenerateUnicodeInfo(string version)
    {
        using FileStream fileStream = GetStreamWriter("UnicodeInfo.Generated.cs");
        using var writer = new StreamWriter(fileStream);

        writer.WriteLine("// Copyright (c) PinataLabs.");
        writer.WriteLine("// Licensed under the Apache License, Version 2.0.");
        writer.WriteLine();
        writer.WriteLine("// <auto-generated />");
        writer.WriteLine("#nullable enable");
        writer.WriteLine("namespace PinataLabs.Typography.Unicode;");
        writer.WriteLine();
        writer.WriteLine("/// <summary>");
        writer.WriteLine("/// Describes the Unicode data that this library is built from.");
        writer.WriteLine("/// </summary>");
        writer.WriteLine("public static class UnicodeInfo");
        writer.WriteLine("{");
        writer.WriteLine("    /// <summary>");
        writer.WriteLine("    /// Gets the version of the Unicode Character Database that the character properties are built from,");
        writer.WriteLine("    /// such as <c>18.0.0</c>.");
        writer.WriteLine("    /// </summary>");
        writer.WriteLine("    /// <remarks>");
        writer.WriteLine("    /// This is a property and not a constant, so that a caller reads the version of the library that is loaded");
        writer.WriteLine("    /// and not the version it was compiled against.");
        writer.WriteLine("    /// </remarks>");
        writer.WriteLine($"    public static string Version => \"{version}\";");
        writer.WriteLine("}");
    }
}
