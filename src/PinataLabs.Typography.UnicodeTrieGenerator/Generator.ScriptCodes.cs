using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;
using PinataLabs.Typography.Unicode;

namespace UnicodeTrieGenerator;

/// <content>
/// Contains code to generate the ISO 15924 code of each script.
/// </content>
public static partial class Generator
{
    /// <summary>
    /// Generates <c>ScriptClassExtensions</c>, which gives the ISO 15924 code of each <see cref="ScriptClass"/>
    /// from the <c>sc</c> lines of <c>PropertyValueAliases.txt</c>.
    /// </summary>
    public static void GenerateScriptCodes()
    {
        // sc ; Zinh ; Inherited ; Qaai: the first name is the ISO 15924 code, the second the long name, and a third is an alias.
        var line = new Regex(@"^sc\s*;\s*(\w+)\s*;\s*(\w+)", RegexOptions.None, TimeSpan.FromSeconds(1));
        var codeByLongName = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        using (StreamReader sr = GetStreamReader("PropertyValueAliases.txt"))
        {
            string? text;
            while ((text = sr.ReadLine()) != null)
            {
                Match match = line.Match(text);
                if (match.Success)
                {
                    codeByLongName.Add(match.Groups[2].Value, match.Groups[1].Value);
                }
            }
        }

        Dictionary<ScriptClass, string> longNames = ScriptMap.ToDictionary(x => x.Value, x => x.Key);
        ScriptClass[] scripts = Enum.GetValues<ScriptClass>();

        using FileStream fileStream = GetStreamWriter("ScriptClassExtensions.Generated.cs");
        using var writer = new StreamWriter(fileStream);

        writer.WriteLine("// Copyright (c) PinataLabs.");
        writer.WriteLine("// Licensed under the Apache License, Version 2.0.");
        writer.WriteLine();
        writer.WriteLine("// <auto-generated />");
        writer.WriteLine("#nullable enable");
        writer.WriteLine("using System;");
        writer.WriteLine();
        writer.WriteLine("namespace PinataLabs.Typography.Unicode;");
        writer.WriteLine();
        writer.WriteLine("/// <summary>");
        writer.WriteLine("/// Provides extension methods for <see cref=\"ScriptClass\"/>.");
        writer.WriteLine("/// </summary>");
        writer.WriteLine("public static class ScriptClassExtensions");
        writer.WriteLine("{");
        writer.WriteLine("    private static readonly string[] Iso15924Codes =");
        writer.WriteLine("    [");

        for (int i = 0; i < scripts.Length; i++)
        {
            ScriptClass script = scripts[i];
            if ((int)script != i)
            {
                throw new InvalidOperationException($"ScriptClass.{script} is {(int)script}, not {i}: the codes are indexed by value.");
            }

            if (!longNames.TryGetValue(script, out string? longName) || !codeByLongName.TryGetValue(longName, out string? code))
            {
                throw new InvalidOperationException($"PropertyValueAliases.txt has no ISO 15924 code for ScriptClass.{script}.");
            }

            writer.WriteLine($"        \"{code}\", // {script}");
        }

        writer.WriteLine("    ];");
        writer.WriteLine();
        writer.WriteLine("    /// <summary>");
        writer.WriteLine("    /// Gets the four-letter ISO 15924 code of a script, such as <c>Latn</c>, <c>Arab</c> or <c>Hebr</c>.");
        writer.WriteLine("    /// </summary>");
        writer.WriteLine("    /// <remarks>");
        writer.WriteLine("    /// The code is the first name of the script in <c>PropertyValueAliases.txt</c>: <c>Zinh</c> for");
        writer.WriteLine("    /// <see cref=\"ScriptClass.Inherited\"/> (<c>Qaai</c> is an alias of it), <c>Zyyy</c> for <see cref=\"ScriptClass.Common\"/>");
        writer.WriteLine("    /// and <c>Zzzz</c> for <see cref=\"ScriptClass.Unknown\"/>.");
        writer.WriteLine("    /// </remarks>");
        writer.WriteLine("    /// <param name=\"script\">The script.</param>");
        writer.WriteLine("    /// <returns>The ISO 15924 code, with an uppercase first letter and lowercase letters after it.</returns>");
        writer.WriteLine("    /// <exception cref=\"ArgumentOutOfRangeException\"><paramref name=\"script\"/> is not a defined value.</exception>");
        writer.WriteLine("    public static string GetIso15924Code(this ScriptClass script)");
        writer.WriteLine("    {");
        writer.WriteLine("        if ((uint)script >= (uint)Iso15924Codes.Length)");
        writer.WriteLine("        {");
        writer.WriteLine("            throw new ArgumentOutOfRangeException(nameof(script), script, null);");
        writer.WriteLine("        }");
        writer.WriteLine();
        writer.WriteLine("        return Iso15924Codes[(int)script];");
        writer.WriteLine("    }");
        writer.WriteLine("}");
    }
}
